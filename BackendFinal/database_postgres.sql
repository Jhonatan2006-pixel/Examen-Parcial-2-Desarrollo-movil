-- Texto que no distingue mayusculas de minusculas. Se usa en el
-- correo para que Jony@correo.com y jony@correo.com sean el mismo.
CREATE EXTENSION IF NOT EXISTS citext;

-- El backend busca las tablas en el esquema "dbo", igual que en SQL Server
CREATE SCHEMA IF NOT EXISTS dbo;

-- 1. Tabla usuarios
CREATE TABLE IF NOT EXISTS dbo.usuarios (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(100)  NOT NULL,
    email       CITEXT        NOT NULL,
    telefono    VARCHAR(20)       NULL,
    password    VARCHAR(255)  NOT NULL,
    created_at  TIMESTAMPTZ       NULL DEFAULT now(),
    CONSTRAINT PK_usuarios       PRIMARY KEY (id),
    CONSTRAINT UQ_usuarios_email UNIQUE (email),
    CONSTRAINT CK_usuarios_email CHECK (char_length(email) <= 150)
);

-- 2. Tabla ubicaciones
--    Cada ubicacion de interes capturada desde la app, asociada
--    al usuario que la guardo.
CREATE TABLE IF NOT EXISTS dbo.ubicaciones (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    usuario_id   INTEGER        NOT NULL,
    nombre       VARCHAR(100)   NOT NULL,
    descripcion  VARCHAR(500)   NOT NULL,
    latitud      NUMERIC(10,7)  NOT NULL,
    longitud     NUMERIC(10,7)  NOT NULL,
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT PK_ubicaciones          PRIMARY KEY (id),
    CONSTRAINT FK_ubicaciones_usuario  FOREIGN KEY (usuario_id)
        REFERENCES dbo.usuarios(id),
    CONSTRAINT CK_ubicaciones_latitud  CHECK (latitud  BETWEEN -90  AND 90),
    CONSTRAINT CK_ubicaciones_longitud CHECK (longitud BETWEEN -180 AND 180)
);

-- Las consultas del listado y del mapa filtran por usuario
CREATE INDEX IF NOT EXISTS IX_ubicaciones_usuario
    ON dbo.ubicaciones (usuario_id, created_at DESC);

-- 3. Permisos del usuario del backend (DB_USER en el archivo .env).
--    Puede leer y modificar los datos, pero no borrar ni cambiar las tablas.
GRANT USAGE ON SCHEMA dbo TO appuser;
GRANT SELECT, INSERT, UPDATE, DELETE
    ON dbo.usuarios, dbo.ubicaciones TO appuser;
